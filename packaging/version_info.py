"""Windows file-properties resource for PyRogue.exe, generated from game/version.py.

Owned by WS-E. The spec calls `write(version, path)` at build time and hands the
resulting text file to EXE(version=...). It is a generator rather than a
committed `version_info.txt` so the version string has exactly one source
(game/version.py, WS-F) and a release can never ship an exe whose Properties
dialog disagrees with its tag.

Standard library only and importable without PyInstaller, so it can be checked
on any OS:  python packaging/version_info.py 1.2.3
"""

import re
import sys
from pathlib import Path

PRODUCT_NAME = 'PyRogue'
COMPANY_NAME = 'PyRogue'
DESCRIPTION = 'PyRogue - a roguelike dungeon crawler'
COPYRIGHT = 'Copyright (c) 2026 Georgy Bodrov. MIT License.'
EXE_NAME = 'PyRogue.exe'


def read_version(version_py):
    """The __version__ string from game/version.py, without importing it."""
    text = Path(version_py).read_text(encoding='utf-8')
    match = re.search(r"""^__version__\s*=\s*['"]([^'"]+)['"]""", text, re.M)
    if not match:
        raise ValueError(f'no __version__ found in {version_py}')
    return match.group(1)


def version_tuple(version):
    """'1.2.3' -> (1, 2, 3, 0). Windows wants exactly four 16-bit integers;
    a pre-release suffix ('0.1.0rc1') is dropped from the numeric form but kept
    in the string fields."""
    match = re.match(r'^(\d+(?:\.\d+){0,3})', version)
    if not match:
        raise ValueError(f'version must start with a number: {version!r}')
    numbers = [int(n) for n in match.group(1).split('.')]
    numbers += [0] * (4 - len(numbers))
    if any(n > 0xFFFF for n in numbers):
        raise ValueError(f'version component too large for Windows: {version!r}')
    return tuple(numbers)


def render(version):
    """The VSVersionInfo text PyInstaller's load_version_info_from_text_file reads."""
    vt = version_tuple(version)

    def s(key, value):
        return f"        StringStruct({key!r}, {value!r}),"

    strings = '\n'.join([
        s('CompanyName', COMPANY_NAME),
        s('FileDescription', DESCRIPTION),
        s('FileVersion', version),
        s('InternalName', PRODUCT_NAME),
        s('LegalCopyright', COPYRIGHT),
        s('OriginalFilename', EXE_NAME),
        s('ProductName', PRODUCT_NAME),
        s('ProductVersion', version),
    ])
    return f"""# UTF-8
# Generated by packaging/version_info.py from game/version.py -- do not edit.
VSVersionInfo(
  ffi=FixedFileInfo(
    filevers={vt},
    prodvers={vt},
    mask=0x3f,
    flags=0x0,
    OS=0x40004,
    fileType=0x1,
    subtype=0x0,
    date=(0, 0)
  ),
  kids=[
    StringFileInfo([
      StringTable(
        '040904B0',
        [
{strings}
        ])
    ]),
    VarFileInfo([VarStruct('Translation', [1033, 1200])])
  ]
)
"""


def write(version, path):
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(render(version), encoding='utf-8')
    return path


if __name__ == '__main__':
    # python packaging/version_info.py                  -> resource text for game/version.py
    # python packaging/version_info.py 1.2.3            -> resource text for 1.2.3
    # python packaging/version_info.py --print-version  -> just the version string
    #   (what build.sh / build.ps1 / release.yml use, so none of them parse
    #   game/version.py themselves)
    root = Path(__file__).resolve().parent.parent
    current = read_version(root / 'game' / 'version.py')
    if sys.argv[1:] == ['--print-version']:
        print(current)
    else:
        print(render(sys.argv[1] if len(sys.argv) > 1 else current))
